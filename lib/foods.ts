export interface FoodRef {
  name: string;
  unit: string;
  unitGrams: number;
  /** per 100 g */
  kcal: number; protein: number; carbs: number; fat: number;
  aliases: string[];
}

export const FOODS: FoodRef[] = ROWS.map(([name, unit, unitGrams, kcal, protein, carbs, fat, aliases]) => ({
  name, unit, unitGrams, kcal, protein, carbs, fat, aliases: aliases ?? [],
}));

const norm = (s: string) => s.replace(/[\s（）()·、，,]/g, "").toLowerCase();
const INDEX = new Map<string, FoodRef>();
for (const f of FOODS) for (const n of [f.name, ...f.aliases]) INDEX.set(norm(n), f);

/** Exact match on the name or an alias. */
export function findFood(name: string): FoodRef | null {
  return INDEX.get(norm(name)) ?? null;
}

/** Nutrition for `grams` of a reference food, rounded like the rest of the app. */
export function nutritionOf(f: FoodRef, grams: number) {
  const k = grams / 100;
  const r = (v: number) => Math.round(v * k * 10) / 10;
  return { calories: Math.round(f.kcal * k), protein: r(f.protein), carbs: r(f.carbs), fat: r(f.fat) };
}

/** Compact list for the AI prompt: "米饭(碗)、糙米饭(碗)…" */
export function foodListForPrompt(): string {
  return FOODS.map(f => `${f.name}(${f.unit})`).join("、");
}
